package com.f2f.entity;

import com.f2f.dbc.entity.BaseEntity;
import com.f2f.enums.TransactionStatus;
import jakarta.persistence.*;
import lombok.Getter;
import lombok.Setter;


import java.io.Serializable;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;

@Getter
@Setter
@Entity
@Table(name = "ACCOUNTING_TRANSACTION",
uniqueConstraints = {@UniqueConstraint(columnNames = {"COMPANY_ID","BRANCH_ID","PERIOD_ID","TRANSACTION_NUMBER"})
})
public class AccountingTransaction extends BaseEntity implements Serializable {

    @Column(name = "TRANSACTION_NUMBER",nullable = false)
    private String transactionNumber;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "PERIOD_ID",nullable = false)
    private AccountingPeriod accountingPeriod;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private TransactionStatus transactionStatus;

    @Column(name = "postedDate")
    private LocalDate postedDate;

    @Column(name = "postedBy")
    private Long postedBy;

    @Column(name = "approvedBy")
    private Long approvedBy;

    @Column(name = "autoGenerated")
    private Boolean autoGenerated = false;


    @OneToOne
    @JoinColumn(name = "TRANSACTION_TYPE_ID")
    private AccountTransactionType accountTransactionType;

    @Column(name = "DESCRIPTION")
    private String description ;

    @Column(name = "ADDITIONAL_DATA")
    private String additionalInfo;

    @Column(name = "ENTRY_DATE")
    private LocalDate entryDate;

    @Column(name = "TRANSACTION_DATE")
    private LocalDate transactionDate;

    @OneToMany(mappedBy = "accountingTransaction")
    private List<AccountTransactionDetail> accountTransactionDetails = new ArrayList<AccountTransactionDetail>();

    @OneToMany(mappedBy = "transaction", cascade = CascadeType.ALL, fetch = FetchType.EAGER)
    private List<AccountingTransactionLog> logs = new ArrayList<>();


    @Column(name = "SOURCE_MODULE")
    private String sourceModule; // INVOICE, PAYMENT, INVENTORY, HR...

    @Column(name = "SOURCE_ID")
    private Long sourceId;       // شناسه اصلی رکورد منبع

    public String getTransactionNumber() {
        return transactionNumber;
    }

    public void setTransactionNumber(String transactionNumber) {
        this.transactionNumber = transactionNumber;
    }

    public AccountingPeriod getAccountingPeriod() {
        return accountingPeriod;
    }

    public void setAccountingPeriod(AccountingPeriod accountingPeriod) {
        this.accountingPeriod = accountingPeriod;
    }

    public TransactionStatus getTransactionStatus() {
        return transactionStatus;
    }

    public void setTransactionStatus(TransactionStatus transactionStatus) {
        this.transactionStatus = transactionStatus;
    }

    public LocalDate getPostedDate() {
        return postedDate;
    }

    public void setPostedDate(LocalDate postedDate) {
        this.postedDate = postedDate;
    }

    public Long getPostedBy() {
        return postedBy;
    }

    public void setPostedBy(Long postedBy) {
        this.postedBy = postedBy;
    }

    public Long getApprovedBy() {
        return approvedBy;
    }

    public void setApprovedBy(Long approvedBy) {
        this.approvedBy = approvedBy;
    }

    public Boolean getAutoGenerated() {
        return autoGenerated;
    }

    public void setAutoGenerated(Boolean autoGenerated) {
        this.autoGenerated = autoGenerated;
    }

    public AccountTransactionType getAccountTransactionType() {
        return accountTransactionType;
    }

    public void setAccountTransactionType(AccountTransactionType accountTransactionType) {
        this.accountTransactionType = accountTransactionType;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getAdditionalInfo() {
        return additionalInfo;
    }

    public void setAdditionalInfo(String additionalInfo) {
        this.additionalInfo = additionalInfo;
    }

    public LocalDate getEntryDate() {
        return entryDate;
    }

    public void setEntryDate(LocalDate entryDate) {
        this.entryDate = entryDate;
    }

    public LocalDate getTransactionDate() {
        return transactionDate;
    }

    public void setTransactionDate(LocalDate transactionDate) {
        this.transactionDate = transactionDate;
    }

    public List<AccountTransactionDetail> getAccountTransactionDetails() {
        return accountTransactionDetails;
    }

    public void setAccountTransactionDetails(List<AccountTransactionDetail> accountTransactionDetails) {
        this.accountTransactionDetails = accountTransactionDetails;
    }

    public List<AccountingTransactionLog> getLogs() {
        return logs;
    }

    public void setLogs(List<AccountingTransactionLog> logs) {
        this.logs = logs;
    }

    public String getSourceModule() {
        return sourceModule;
    }

    public void setSourceModule(String sourceModule) {
        this.sourceModule = sourceModule;
    }

    public Long getSourceId() {
        return sourceId;
    }

    public void setSourceId(Long sourceId) {
        this.sourceId = sourceId;
    }

    public void setStatus(TransactionStatus transactionStatus) {

    }

    public void setPeriod(AccountingPeriod period) {

    }

    public void setNumber(int i) {

    }

    public boolean getStatus() {
        return true;
    }
}
